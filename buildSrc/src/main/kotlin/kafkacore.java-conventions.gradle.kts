// Shared conventions applied to every KafkaCore Lab module (see ADR-0002).
plugins {
    java
    jacoco
}

group = "io.kafkacore.lab"
version = "1.0.0"

repositories {
    mavenCentral()
}

java {
    toolchain {
        languageVersion.set(JavaLanguageVersion.of(17))
    }
}

val libs = the<org.gradle.accessors.dm.LibrariesForLibs>()

dependencies {
    testImplementation(platform(libs.junit.bom))
    testImplementation(libs.junit.jupiter)
    testImplementation(libs.assertj)
    testRuntimeOnly(libs.junit.platform.launcher)
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    options.release.set(17)
    options.compilerArgs.addAll(listOf("-Xlint:all,-serial,-processing,-path,-options", "-Werror"))
}

tasks.test {
    useJUnitPlatform {
        // Unit tests never need Docker. Anything touching a real cluster is tagged "integration"
        // and lives in the kafkacore-it module (see ADR-0009).
        excludeTags("integration")
    }
    testLogging {
        events("passed", "skipped", "failed")
        showStandardStreams = false
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
    }
    finalizedBy(tasks.jacocoTestReport)
}

tasks.jacocoTestReport {
    reports {
        xml.required.set(true)
        html.required.set(true)
    }
}
